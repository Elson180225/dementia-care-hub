// Shared field definitions drive Admin forms and server-side allowlists.
const text = (key, label, required = false) => ({
  key,
  label,
  required,
  type: "text",
});
const area = (key, label, required = false) => ({
  ...text(key, label, required),
  type: "textarea",
});
const select = (key, label, options, required = true) => ({
  key,
  label,
  type: "select",
  options,
  required,
});
const date = (key, label) => ({ key, label, type: "date" });
const number = (key, label, required = false) => ({
  key,
  label,
  type: "number",
  required,
});
const check = (key, label) => ({ key, label, type: "checkbox" });
